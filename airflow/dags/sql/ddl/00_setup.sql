-- Already applied in the personal trial (18 Nov), kept here so the repo can recreate it.
-- Run as ACCOUNTADMIN (or a role that can create warehouse/database/schema).

CREATE WAREHOUSE IF NOT EXISTS PO_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
       AUTO_SUSPEND = 60
       AUTO_RESUME = TRUE
       INITIALLY_SUSPENDED = TRUE;

-- Set a credit usage limit
CREATE RESOURCE MONITOR IF NOT EXISTS PO_COST_MONITOR
WITH
    CREDIT_QUOTA = 10
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 50 PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE PO_WH SET RESOURCE_MONITOR = PO_COST_MONITOR;

CREATE DATABASE IF NOT EXISTS PURCHASE_ORDER_DB;

CREATE SCHEMA IF NOT EXISTS PURCHASE_ORDER_DB.RAW;
CREATE SCHEMA IF NOT EXISTS PURCHASE_ORDER_DB.CORE;
CREATE SCHEMA IF NOT EXISTS PURCHASE_ORDER_DB.MART;

USE DATABASE PURCHASE_ORDER_DB;
USE WAREHOUSE PO_WH;
